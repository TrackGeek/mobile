String franchiseSlug(int id, String name) {
  final buffer = StringBuffer();
  var lastDash = false;
  for (final unit in name.toLowerCase().codeUnits) {
    var char = String.fromCharCode(unit);
    char = _diacritics[char] ?? char;
    if (char.length == 1 && RegExp('[a-z0-9]').hasMatch(char)) {
      buffer.write(char);
      lastDash = false;
    } else {
      for (final sub in char.codeUnits) {
        final c = String.fromCharCode(sub);
        if (RegExp('[a-z0-9]').hasMatch(c)) {
          buffer.write(c);
          lastDash = false;
        }
      }
      if (!lastDash && buffer.isNotEmpty) {
        buffer.write('-');
        lastDash = true;
      }
    }
  }
  var slug = buffer.toString();
  if (slug.endsWith('-')) slug = slug.substring(0, slug.length - 1);
  return slug.isEmpty ? '$id' : '$id-$slug';
}
